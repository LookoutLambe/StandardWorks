// WHICH GAPS ARE NOT BIBLICAL HEBREW?
// The analyser resolves to biblical roots, so words with no biblical root are
// out of scope: it can only ever guess at them. Signals, strongest first:
//   1. the root the analyser proposes has ZERO attestation in the Masoretic
//      text (ot_verses) -- a biblical root always occurs there
//   2. the form occurs ONLY in the restoration/NT volumes, never in the MT
//   3. distinctly post-biblical morphology: של possessive, ־וּת abstracts
const fs=require("fs"),path=require("path"),vm=require("vm");
const M=require("../mishkal.js"), R=require("../radical.js");
const HEU=require("../morph.js"), PAR=require("../morph2.js");
const strip=s=>[...s].filter(c=>!(c.codePointAt(0)>=0x0591&&c.codePointAt(0)<=0x05C7)).join("");
const FIN={"ך":"כ","ם":"מ","ן":"נ","ף":"פ","ץ":"צ"};
const norm=s=>[...strip(s)].map(c=>FIN[c]||c).join("");
const {roots}=JSON.parse(fs.readFileSync(process.argv[2],"utf8"));
const KNOWN=new Set(roots.map(norm));
const win={};
["strongs_lookup.js","strongs_roots.js","bdb_roots.js","shoroshim_roots.js","root_names.js"]
  .forEach(f=>vm.runInNewContext(fs.readFileSync(f,"utf8"),{window:win},{filename:f}));
const ctx={window:win,_strongsLookup:win._strongsLookup,_strongsRoots:win._strongsRoots};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("root_engine.js","utf8"),ctx,{filename:"root_engine.js"});
const getRoot=win.RootEngine.getRoot;
const sb={console}; sb.window=sb; vm.createContext(sb);
vm.runInContext(fs.readFileSync("root_concordance.js","utf8"),sb);
const RC=sb._rootConcordance,FREQ=new Map(),VOLIDX=RC.vols||[];
RC.keys.forEach((k,i)=>FREQ.set(norm(k),RC.roots[i].c.reduce((a,b)=>a+b,0)));
// PREFER THE LEXICON PRIOR. root_concordance.js is generated by the resolver
// being fixed, so it records נתן at 7 and כון at 6 -- a feedback loop that made
// the ranking choose יתן over נתן. lexfreq counts Strong's forms per BDB root
// and never touches the engine. Concordance stays as the fallback for the
// ~1,900 roots BDB does not map.
try{ const LF=require("../lexfreq.js").build();
     for(const [k,v] of LF) FREQ.set(k, Math.max(v*8, FREQ.get(k)||0)); }catch(e){}
// --- root frequency IN THE MASORETIC TEXT ONLY -------------------------
const TOK=/\["([^"]*)","([^"]*)"\]/g;
const mtRoots=new Map(), mtForms=new Set();
for(const f of fs.readdirSync("ot_verses")){
  if(!f.endsWith(".js")) continue;
  const src=fs.readFileSync(path.join("ot_verses",f),"utf8"); let m;
  while((m=TOK.exec(src))){
    const h=m[1]; if(!norm(h)) continue;
    mtForms.add(norm(h));
    let r; try{ r=norm(String(getRoot(h))); }catch(e){ continue; }
    mtRoots.set(r,(mtRoots.get(r)||0)+1);
  }
}
console.log("  Masoretic text: "+mtForms.size+" distinct forms, "+mtRoots.size+" distinct root keys\n");
const heu=HEU.makeAnalyzer(KNOWN,FREQ), par=PAR.makeAnalyzer(KNOWN,FREQ);
function propose(f){
  const m=M.analyze(f,KNOWN,FREQ);
  if(m&&m.how!=="mishkal:katal") return m.r;
  const r=R.analyze(f,KNOWN,FREQ); if(r) return r.r;
  if(m) return m.r;
  return heu(f)||par(f)||null;
}
const rows=fs.readFileSync("engine_gaps.tsv","utf8").trim().split("\n").slice(1).map(l=>l.split("\t"));
let biblical=0, modern=0, tokB=0, tokM=0;
const ex=[];
for(const [n,vol,ref,form,gloss] of rows){
  const c=norm(form.split("־").pop());
  const inMT = mtForms.has(c);
  const r = propose(form);
  const rootInMT = r ? (mtRoots.get(norm(r))||0) > 0 : false;
  const modernShape = /^של/.test(c) || /ות$/.test(c)&&c.length>=6;
  const isModern = !inMT && !rootInMT;
  if(isModern){ modern++; tokM+=+n; if(ex.length<18) ex.push({n:+n,vol,form,gloss,r:r||"-"}); }
  else { biblical++; tokB+=+n; }
}
console.log("  gap rows: "+rows.length);
console.log("    root attested in the MT (biblical, in scope) : "+biblical+"  ("+tokB+" tokens)");
console.log("    NO MT attestation (post-biblical, out of scope): "+modern+"  ("+tokM+" tokens)");
console.log("\n  === samples of the out-of-scope set ===");
for(const e of ex) console.log("   x"+String(e.n).padEnd(3)+e.vol.padEnd(11)+e.form.padEnd(22)+'"'+e.gloss.slice(0,26)+'"');
