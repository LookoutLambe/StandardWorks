// The review queue: every Hebrew-only engine gap with the radical analyser's
// proposal AND the rule that produced it, so each row can be judged on sight.
const fs=require("fs"),vm=require("vm");
const R=require("../radical.js");
const HEU=require("../morph.js"), PAR=require("../morph2.js");
const strip=s=>[...s].filter(c=>!(c.codePointAt(0)>=0x0591&&c.codePointAt(0)<=0x05C7)).join("");
const FIN={"ך":"כ","ם":"מ","ן":"נ","ף":"פ","ץ":"צ"};
const norm=s=>[...strip(s)].map(c=>FIN[c]||c).join("");
const {roots}=JSON.parse(fs.readFileSync(process.argv[2],"utf8"));
const KNOWN=new Set(roots.map(norm));
const win={};
["strongs_roots.js","root_names.js"].forEach(f=>vm.runInNewContext(fs.readFileSync(f,"utf8"),{window:win},{filename:f}));
const SR=win._strongsRoots, NAMES=win._rootProperNames;
const sb={console}; sb.window=sb; vm.createContext(sb);
vm.runInContext(fs.readFileSync("root_concordance.js","utf8"),sb);
const RC=sb._rootConcordance,FREQ=new Map();
RC.keys.forEach((k,i)=>FREQ.set(norm(k),RC.roots[i].c.reduce((a,b)=>a+b,0)));
// PREFER THE LEXICON PRIOR. root_concordance.js is generated by the resolver
// being fixed, so it records נתן at 7 and כון at 6 -- a feedback loop that made
// the ranking choose יתן over נתן. lexfreq counts Strong's forms per BDB root
// and never touches the engine. Concordance stays as the fallback for the
// ~1,900 roots BDB does not map.
try{ const LF=require("../lexfreq.js").build();
     for(const [k,v] of LF) FREQ.set(k, Math.max(v*8, FREQ.get(k)||0)); }catch(e){}
let GL={};
try{ const g={}; vm.runInNewContext(fs.readFileSync("bom/roots_glossary.js","utf8"),{window:g},{filename:"g"});
     GL=g._rootGlossaryData||g._rootsGlossary||{}; }catch(e){}
const mean=r=>{ if(GL[r]) return String(GL[r].m||GL[r].meaning||GL[r]||"").replace(/\s+/g," ").slice(0,44);
  for(const k in SR){ const x=SR[k]; if(x&&norm(x.w)===norm(r)) return String(x.g||"").slice(0,44); } return ""; };
// the five markers you named
const IGNORE=new Set(["את","מנ","לא","כל","ואת"]);
let _heu=null,_par=null;
function fallback(f){
  if(!_heu){ _heu=HEU.makeAnalyzer(KNOWN,FREQ); _par=PAR.makeAnalyzer(KNOWN,FREQ); }
  return _heu(f)||_par(f);
}
function resolve(form){
  if(!form.includes("־")){
    const a=R.analyze(form,KNOWN,FREQ);
    if(a) return a;
    const b=fallback(form);
    return b?{r:b,how:"heuristic"}:null;
  }
  const ps=form.split("־").filter(Boolean);
  const kept=ps.filter(p=>!IGNORE.has(norm(p)));
  for(const p of (kept.length?kept:ps)){ const a=R.analyze(p,KNOWN,FREQ); if(a) return a; }
  for(const p of (kept.length?kept:ps)){ const b=fallback(p); if(b) return {r:b,how:"heuristic"}; }
  return null;
}
const rows=fs.readFileSync("engine_gaps.tsv","utf8").trim().split("\n").slice(1).map(l=>l.split("\t"));
const out=[]; let prop=0,noneN=0,nameN=0;
for(const [n,vol,ref,form,gloss] of rows){
  const head=form.split("־").pop();
  if(NAMES[norm(head)]){ nameN++; continue; }          // a name: no root by design
  const a=resolve(form);
  if(a){ prop++; out.push({n:+n,vol,ref,form,gloss,root:a.r,rule:a.how,mean:mean(a.r)}); }
  else { noneN++; out.push({n:+n,vol,ref,form,gloss,root:"",rule:"(no analysis)",mean:""}); }
}
out.sort((a,b)=>b.n-a.n);
console.log("  rows              : "+out.length);
console.log("  with a proposal   : "+prop+"  ("+(100*prop/out.length).toFixed(1)+"%)");
console.log("  no analysis       : "+noneN);
console.log("  skipped as names  : "+nameN);
console.log("\n   x   volume  form                   gloss                      -> root   rule                     root means");
for(const r of out.slice(0,32))
  console.log("   "+String(r.n).padEnd(4)+r.vol.padEnd(8)+r.form.padEnd(23)+r.gloss.slice(0,26).padEnd(27)+"-> "+
              r.root.padEnd(7)+r.rule.slice(0,23).padEnd(24)+r.mean);
fs.writeFileSync(process.argv[3],
 "count\tvolume\tfirst_ref\tform\tgloss\tproposed_root\trule\troot_meaning\n"+
 out.map(r=>[r.n,r.vol,r.ref,r.form,r.gloss,r.root,r.rule,r.mean].join("\t")).join("\n"));
console.log("\n  written: "+process.argv[3]);
