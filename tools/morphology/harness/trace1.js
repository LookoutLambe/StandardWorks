// Show EVERY candidate a word produces, with the peel that made it.
const fs=require("fs"),vm=require("vm");
const M=require("../mishkal.js");
const strip=s=>[...s].filter(c=>!(c.codePointAt(0)>=0x0591&&c.codePointAt(0)<=0x05C7)).join("");
const FIN={"ך":"כ","ם":"מ","ן":"נ","ף":"פ","ץ":"צ"};
const norm=s=>[...strip(s)].map(c=>FIN[c]||c).join("");
const {roots}=JSON.parse(fs.readFileSync(process.argv[2],"utf8"));
const KNOWN=new Set(roots.map(norm));
const sb={console}; sb.window=sb; vm.createContext(sb);
vm.runInContext(fs.readFileSync("root_concordance.js","utf8"),sb);
const RC=sb._rootConcordance,FREQ=new Map();
RC.keys.forEach((k,i)=>FREQ.set(norm(k),RC.roots[i].c.reduce((a,b)=>a+b,0)));
// PREFER THE LEXICON PRIOR. root_concordance.js is generated by the resolver
// being fixed, so it records נתן at 7 and כון at 6 -- a feedback loop that made
// the ranking choose יתן over נתן. lexfreq counts Strong's forms per BDB root
// and never touches the engine. Concordance stays as the fallback for the
// ~1,900 roots BDB does not map.
try{ const LF=require("../lexfreq.js").build();
     for(const [k,v] of LF) FREQ.set(k, Math.max(v*8, FREQ.get(k)||0)); }catch(e){}
const PROC=["","ו","ב","כ","ל","מ","ה","ש","וב","וכ","ול","ומ","וה","וש","לה","בה","כה","מה"];
const ENCL=["","י","ו","ך","ה","ם","נ","נו","הו","הם","הן","כם","כן","יו","יה","יך","ים","ות","תי","ינו","יהם","יכם"];
function trace(form){
  const c0=M.cons(form);
  console.log("\n  "+form+"   consonants = "+c0);
  const rows=[];
  for(const p of PROC){
    if(p&&!c0.startsWith(p)) continue;
    const a=c0.slice(p.length);
    for(const e of ENCL){
      if(e&&!a.endsWith(e)) continue;
      const body=e?a.slice(0,-e.length):a;
      if(body.length<3||body.length>6) continue;
      for(const [name,tpl] of M.PATTERNS){
        const toks=tpl.split(" ").filter(Boolean);
        if(toks.length!==body.length) continue;
        const R={}; let ok=true;
        for(let i=0;i<toks.length;i++){
          const t=toks[i], ch=body[i];
          if(/^[123]$/.test(t)){ if(R[t]&&R[t]!==ch){ok=false;break;} R[t]=ch; }
          else if(t!==ch){ok=false;break;}
        }
        if(!ok) continue;
        const r=(R["1"]&&R["2"]&&R["3"])?R["1"]+R["2"]+R["3"]:null;
        if(!r||!KNOWN.has(r)) continue;
        rows.push({p,e,body,name,r,d:p.length+e.length,f:FREQ.get(r)||0});
      }
    }
  }
  rows.sort((a,b)=> a.d!==b.d ? a.d-b.d : b.f-a.f);
  console.log("     peel-off        stem      pattern        root   depth  freq");
  for(const r of rows.slice(0,10))
    console.log("     "+("p="+(r.p||"-")+" s="+(r.e||"-")).padEnd(16)+r.body.padEnd(10)+r.name.padEnd(15)+r.r.padEnd(7)+String(r.d).padEnd(7)+r.f);
  if(rows.length) console.log("     WINNER: "+rows[0].r+"  ["+rows[0].name+"]  (peeled "+(rows[0].p||"nothing")+" off the front)");
}
for(const f of process.argv.slice(3)) trace(f);
