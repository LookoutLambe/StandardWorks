#!/usr/bin/env node
/**
 * build_jst_refmap.js — "JST Genesis 9" -> the chapter panel that holds it.
 *
 * The JST's chapter ids are FILE POSITIONS, not chapter numbers: jstgen-ch2 is
 * JST Genesis 9, jst1co-ch2 is 1 Corinthians 15. The real reference is recorded
 * only in a source comment above each verse set —
 *
 *     // === CH2: JST Genesis 9 ===
 *
 * — so nothing could follow a "JST Gen. 9:15" cross-reference: 184 of them
 * across the corpus rendered as inert text. This lifts those comments into a
 * lookup table so the reference resolves like any other.
 *
 * Regenerate whenever jst_verses/ changes; the pre-commit hook does it.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const DIR = path.join(ROOT, 'jst_verses');

const map = {};
let panels = 0, labelled = 0;
const skipped = [];

for (const file of fs.readdirSync(DIR).sort()) {
  if (!file.endsWith('.js') || file === 'manifest.js') continue;
  const book = file.replace(/\.js$/, '');
  const src = fs.readFileSync(path.join(DIR, file), 'utf8');
  panels += new Set([...src.matchAll(/'([a-z0-9]+-ch\d+)-verses'/g)].map(m => m[1])).size;

  for (const m of src.matchAll(/===\s*CH(\d+):\s*([^=]*?)\s*===/g)) {
    const id = book + '-ch' + m[1];
    const label = m[2].trim();
    /* "JST Genesis 9", "JST, Genesis 9:4–6", "JST Matthew 5 (Appendix)" —
       the book name and its FIRST chapter number are all that is needed. */
    const hit = label.match(/^JST[,]?\s+(.+?)\s+(\d+)/);
    if (!hit) { skipped.push(id + ' :: ' + label); continue; }
    const key = hit[1].trim() + ' ' + hit[2];
    if (!map[key]) map[key] = id;          // first panel wins
    labelled++;
  }
}

const out =
  '/* GENERATED by tools/build_jst_refmap.js — do not edit.\n' +
  '   "JST Genesis 9" -> the chapter panel holding it. The JST\'s chapter ids\n' +
  '   are file positions, not chapter numbers, and the real reference lives\n' +
  '   only in a source comment; this is that comment, made usable. */\n' +
  'window._jstRefMap = ' + JSON.stringify(map, null, 1) + ';\n';
fs.writeFileSync(path.join(ROOT, 'jst_refmap.js'), out);

console.log('[jst-refmap] ' + Object.keys(map).length + ' references mapped from ' +
            labelled + ' labelled panels (' + panels + ' panels total)');
if (skipped.length) {
  console.log('[jst-refmap] ' + skipped.length + ' panel(s) with no JST label (expected for pointers):');
  skipped.forEach(s => console.log('             ' + s));
}
