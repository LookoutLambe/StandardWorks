// build_verse_manifests.js — the data behind the readers' lazy volume loader.
//
// For each of the five volumes served by reader_core.js it writes:
//   <vol>_verses/manifest.js   window.READER_VERSE_MANIFEST = { prefixes, ids, files, english }
//                              chapter-id prefix ('gen-ch') or exact id ('dc-intro') → verse file
//   <vol>_english/<file>       the volume's English rows for the chapters that file
//                              holds, as registerEnglish([...]) — loaded with the book
//                              only when the Dual view is on
//
// Source of truth stays where it is: the verse files register their chapters
// through renderVerseSet(data, '<id>-verses'), and <vol>_english.js holds the
// English rows. This tool only derives; it never edits either. Run it after any
// change to a verse file or an English file (the pre-commit hook does).
//
// A verse file that registers no chapter (dc_verses/dc_chron.js, a table) is
// reported and left to the page as a static tag. An English row whose chapter
// no verse file registers is an ERROR, not a silent drop.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const REG = /renderVerseSet\(\s*[\w$]+\s*,\s*['"]([^'"]+)-verses['"]/g;
const TABLE = /\{\s*prefix\s*:\s*'([^']+)'[^}]*?\ben\s*:\s*'([^']+)'/g;

// (book name in <vol>_english.js, chapter) → chapter id
const RULES = {
  ot:  { page: 'ot.html' },
  nt:  { page: 'nt.html' },
  jst: { page: 'jst.html' },
  pgp: { page: 'pgp.html', extra: { 'Abraham-Facsimile': ch => 'ab-fac' + ch, 'PGP-Introduction': () => 'pgp-intro' } },
  dc:  { extra: { 'D&C': ch => 'dc' + ch + '-ch1', 'OD': ch => 'od' + ch + '-ch1' } }
};

let failed = false;
for (const vol of Object.keys(RULES)) {
  const dir = path.join(ROOT, vol + '_verses');
  const files = fs.readdirSync(dir).filter(f => /\.js$/.test(f) && f !== 'manifest.js').sort();
  const prefixes = {}, ids = {}, byFile = {}, silent = [];
  for (const f of files) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8'); let m, n = 0; REG.lastIndex = 0;
    while ((m = REG.exec(src))) {
      const id = m[1]; n++;
      const key = /\d$/.test(id) ? id.replace(/\d+$/, '') : id;
      const table = /\d$/.test(id) ? prefixes : ids;
      if (table[key] && table[key] !== f) { console.error(`${vol}: ${key} registered by both ${table[key]} and ${f}`); failed = true; }
      table[key] = f;
      (byFile[f] = byFile[f] || []).push(id);
    }
    if (!n) silent.push(f);
  }
  // English chunks
  const rule = RULES[vol]; const bookPrefix = {};
  if (rule.page) { const h = fs.readFileSync(path.join(ROOT, rule.page), 'utf8'); let t; TABLE.lastIndex = 0; while ((t = TABLE.exec(h))) bookPrefix[t[2]] = t[1]; }
  const engPath = path.join(ROOT, vol + '_english.js');
  const eng = fs.readFileSync(engPath, 'utf8');
  const rows = JSON.parse(eng.slice(eng.indexOf('['), eng.lastIndexOf(']') + 1));
  const chunks = {}, unplaced = [];
  for (const r of rows) {
    let id = null;
    if (rule.extra && rule.extra[r.book]) id = rule.extra[r.book](r.chapter);
    else if (bookPrefix[r.book]) { const p = bookPrefix[r.book]; id = (prefixes[p] ? p : p + '-ch') + r.chapter; } // ot/nt tables say 'gen', pgp/jst say 'ab-ch'
    const file = id ? (ids[id] || prefixes[id.replace(/\d+$/, '')]) : null;
    if (!file) { unplaced.push(r.book + ' ' + r.chapter + ':' + r.verse); continue; }
    (chunks[file] = chunks[file] || []).push([r.book, r.chapter, r.verse, r.english]);
  }
  const outDir = path.join(ROOT, vol + '_english');
  fs.mkdirSync(outDir, { recursive: true });
  for (const stale of fs.readdirSync(outDir)) if (!chunks[stale]) fs.unlinkSync(path.join(outDir, stale));
  let bytes = 0;
  for (const f of Object.keys(chunks)) {
    const txt = '// generated by tools/build_verse_manifests.js from ' + vol + '_english.js — Dual-view English for the chapters of ' + vol + '_verses/' + f + '\n' +
      'registerEnglish(' + JSON.stringify(chunks[f]) + ');\n';
    fs.writeFileSync(path.join(outDir, f), txt); bytes += txt.length;
  }
  // `english` names the files that have a chunk — an introduction or a table has none, and the loader must never ask for one.
  const manifest = { prefixes, ids, files: Object.keys(byFile), english: Object.keys(chunks).sort() };
  fs.writeFileSync(path.join(dir, 'manifest.js'),
    '// generated by tools/build_verse_manifests.js — which verse file holds which chapter, and which files carry Dual English\n' +
    'window.READER_VERSE_MANIFEST = ' + JSON.stringify(manifest) + ';\n');
  console.log(`${vol}: ${files.length} verse files, ${Object.keys(prefixes).length} prefixes + ${Object.keys(ids).length} ids, english ${rows.length} rows → ${Object.keys(chunks).length} chunks (${(bytes / 1048576).toFixed(2)} MB)` +
    (silent.length ? `; static (no chapters): ${silent.join(', ')}` : ''));
  if (unplaced.length) { console.error(`${vol}: ${unplaced.length} English rows have no verse file: ${unplaced.slice(0, 8).join(' | ')}`); failed = true; }
}
if (failed) { console.error('build_verse_manifests: FAILED'); process.exit(1); }
