#!/usr/bin/env node
/* Split <vol>_crossrefs.js into one chunk per verse file, and list the chunks
   in the volume's verse manifest.
   ---------------------------------------------------------------------------
   The cross-reference map was one whole-corpus file per volume — 1.24 MB for
   the OT, 41% of that page's bytes — fetched in full to mark up ONE chapter.
   It is split here exactly the way tools/build_heading_manifests.js splits the
   chapter summaries: keyed by the verse file that holds the book, so the
   chunk arrives with the book the reader actually opened.

   THE BOOK NAME IS THE SITE'S OWN. The verse key the reader looks up is built
   from READER.books[].en, so a chunk keyed by any other name is dead weight:
   the OT data said "Song of Solomon" where the reader says "Song of Songs",
   and every cross-reference in that book had been invisible. Names are
   canonicalised against the page's own book table here, and any rename is
   reported rather than applied silently.

   Run: node tools/build_crossref_chunks.js        (the pre-commit hook does)  */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const VOLS = [
  { vol: 'ot',  page: 'ot.html'  },
  { vol: 'nt',  page: 'nt.html'  },
  { vol: 'dc',  page: 'dc.html'  },
  { vol: 'pgp', page: 'pgp.html' },
];

/* The data and manifest files are plain `window.X = {...}` assignments. */
function loadGlobals(file) {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(file, 'utf8'), sandbox, { filename: file });
  return sandbox.window;
}

/* READER.books lives in the page as a JS array literal. The D&C's is empty —
   its "books" are numbered sections, so the chapter number IS the section. */
function booksOf(page) {
  const src = fs.readFileSync(page, 'utf8');
  const m = src.match(/var [A-Z_0-9]*BOOKS = (\[[\s\S]*?\n\];)/);
  if (!m) return [];
  const sandbox = {}; vm.createContext(sandbox);
  return vm.runInContext('(' + m[1].replace(/;$/, '') + ')', sandbox);
}

/* Names the source data uses for a book this site calls something else. */
const BOOK_ALIAS = { 'Song of Solomon': 'Song of Songs' };

let failed = false;

for (const v of VOLS) {
  const dataFile = path.join(ROOT, v.vol + '_crossrefs.js');
  const manFile  = path.join(ROOT, v.vol + '_verses', 'manifest.js');
  if (!fs.existsSync(dataFile) || !fs.existsSync(manFile)) continue;

  const data  = loadGlobals(dataFile)['_' + v.vol + 'CrossrefsData'];
  const man   = loadGlobals(manFile).READER_VERSE_MANIFEST;
  const books = booksOf(path.join(ROOT, v.page));
  const byEn  = {};
  books.forEach(b => { byEn[b.en] = b.prefix; });

  const fileFor = id => (man.ids && man.ids[id]) || man.prefixes[id.replace(/\d+$/, '')] || null;
  /* D&C sections have no book table: "D&C|76|24" is section 76, chapter id dc76-ch1.
     Book prefixes are written both ways across the pages — the OT's is bare
     ("gen"), the Pearl's already carries the suffix ("ms-ch") — so append only
     what is missing rather than assuming either shape. */
  const chapIdFor = (book, ch) => {
    if (v.vol === 'dc') return 'dc' + ch + '-ch1';
    const p = byEn[book];
    if (!p) return null;
    return (/-ch$/.test(p) ? p : p + '-ch') + ch;
  };

  const perFile = {}, renamed = {}, unmapped = {};
  let kept = 0;
  for (const key of Object.keys(data)) {
    const parts = key.split('|');
    const raw = parts[0];
    const book = BOOK_ALIAS[raw] || raw;
    if (book !== raw) renamed[raw] = (renamed[raw] || 0) + 1;
    const id = chapIdFor(book, parts[1]);
    const f  = id ? fileFor(id) : null;
    if (!f) { unmapped[raw] = (unmapped[raw] || 0) + 1; continue; }
    (perFile[f] = perFile[f] || {})[[book, parts[1], parts[2]].join('|')] = data[key];
    kept++;
  }

  if (Object.keys(unmapped).length) {
    console.error(`  ${v.vol}: UNMAPPED BOOKS ${JSON.stringify(unmapped)} — no verse file holds them`);
    failed = true;
    continue;
  }

  const outDir = path.join(ROOT, v.vol + '_crossrefs');
  fs.mkdirSync(outDir, { recursive: true });
  /* A chunk left behind by a rename would keep being served and never read. */
  for (const stale of fs.readdirSync(outDir)) {
    if (stale.endsWith('.js') && !perFile[stale]) fs.unlinkSync(path.join(outDir, stale));
  }

  const global = '_' + v.vol + 'CrossrefsData';
  const files = Object.keys(perFile).sort();
  let bytes = 0;
  for (const f of files) {
    /* Self-merging and order-independent, like the heading chunks: whichever
       arrives first creates the object, and crossrefs_engine picks it up when
       it next runs — no chunk depends on the engine being loaded yet. */
    const body = '// generated by tools/build_crossref_chunks.js — cross-references for ' + f + '\n'
      + '(function(){ var W = window;\n'
      + '  Object.assign(W.' + global + ' = W.' + global + ' || {}, '
      + JSON.stringify(perFile[f]) + ');\n'
      + '  if (typeof W.__swCrossrefsArrived === \'function\') W.__swCrossrefsArrived();\n'
      + '})();\n';
    fs.writeFileSync(path.join(outDir, f), body);
    bytes += Buffer.byteLength(body);
  }

  /* The manifest is the one place that says which chunks exist. */
  const manSrc = fs.readFileSync(manFile, 'utf8');
  const obj = loadGlobals(manFile).READER_VERSE_MANIFEST;
  obj.crossrefs = files;
  const header = manSrc.slice(0, manSrc.indexOf('window.READER_VERSE_MANIFEST'));
  const note = header.includes('crossrefs[]') ? header
    : header + '// crossrefs[] added by tools/build_crossref_chunks.js — which files have a cross-reference chunk\n';
  fs.writeFileSync(manFile, note + 'window.READER_VERSE_MANIFEST = ' + JSON.stringify(obj) + ';\n');

  const whole = fs.statSync(dataFile).size;
  const largest = files.map(f => fs.statSync(path.join(outDir, f)).size).sort((a, b) => b - a)[0];
  console.log(`  ${v.vol}: ${kept} keys → ${files.length} chunks  `
    + `(was ${(whole / 1024).toFixed(0)} KB in one file; largest chunk ${(largest / 1024).toFixed(0)} KB)`
    + (Object.keys(renamed).length ? `  renamed ${JSON.stringify(renamed)}` : ''));
}

/* ── The Book of Mormon ─────────────────────────────────────────────────────
   Same job, different plumbing. bom.html has no READER.books and no verse
   manifest — it maps a chapter id to a book script through BOOK_RULES in
   bom/bom_book_loader.js — so the two tables it does have are read here and
   composed: BOOK_DATA gives book name -> chapter-id prefix, BOOK_RULES gives
   a chapter id -> verses/<slug>.js. Nothing new is invented; a book that
   cannot be resolved through both fails the build.

   Two maps, not one: crossrefs.js is what this verse cites (785 KB, and it was
   a BLOCKING <script>), bom_inverse_crossrefs.js is what cites this verse from
   the other volumes (632 KB, deferred but always whole). Both are keyed
   Book|Chapter|Verse and both are only ever read for a verse on screen. */
{
  const bomHtml = fs.readFileSync(path.join(ROOT, 'bom', 'bom.html'), 'utf8');
  const loader  = fs.readFileSync(path.join(ROOT, 'bom', 'bom_book_loader.js'), 'utf8');

  const bdm = bomHtml.match(/var BOOK_DATA = (\[[\s\S]*?\n\];)/);
  if (!bdm) { console.error('  bom: BOOK_DATA not found in bom.html'); failed = true; }
  else {
    const sb = {}; vm.createContext(sb);
    const BOOK_DATA = vm.runInContext('(' + bdm[1].replace(/;$/, '') + ')', sb);

    /* BOOK_RULES is a list of {match(id), src}. Running it verbatim keeps the
       loader the single authority on which chapter belongs to which file. */
    const lb = { window: {}, module: {}, global: {} }; vm.createContext(lb);
    vm.runInContext(loader, lb, { filename: 'bom_book_loader.js' });
    const scriptFor = lb.window.bomBookScriptForChapId;
    if (typeof scriptFor !== 'function') {
      console.error('  bom: bom_book_loader.js did not export bomBookScriptForChapId');
      failed = true;
    } else {
      const slugFor = {};                       // "Alma" -> "alma"
      for (const b of BOOK_DATA) {
        const src = scriptFor(b.prefix + '1');  // e.g. al-ch1 -> verses/alma.js?v=4
        const m = src && src.match(/verses\/([^.?]+)\.js/);
        if (m) slugFor[b.name] = m[1];
      }

      const MAPS = [
        { file: 'bom/crossrefs.js',              global: '_crossrefsData',       dir: 'bom/crossrefs' },
        { file: 'bom/bom_inverse_crossrefs.js',  global: '_bomInverseXrefsData', dir: 'bom/inverse_crossrefs' },
      ];
      for (const M of MAPS) {
        const data = loadGlobals(path.join(ROOT, M.file))[M.global];
        const perBook = {}, unmapped = {};
        for (const key of Object.keys(data)) {
          const book = key.split('|')[0];
          const slug = slugFor[book];
          if (!slug) { unmapped[book] = (unmapped[book] || 0) + 1; continue; }
          (perBook[slug] = perBook[slug] || {})[key] = data[key];
        }
        if (Object.keys(unmapped).length) {
          console.error(`  bom ${M.global}: UNMAPPED BOOKS ${JSON.stringify(unmapped)}`);
          failed = true;
          continue;
        }
        const outDir = path.join(ROOT, M.dir);
        fs.mkdirSync(outDir, { recursive: true });
        for (const stale of fs.readdirSync(outDir)) {
          if (stale.endsWith('.js') && !perBook[stale.replace(/\.js$/, '')]) {
            fs.unlinkSync(path.join(outDir, stale));
          }
        }
        const slugs = Object.keys(perBook).sort();
        let bytes = 0, largest = 0;
        for (const slug of slugs) {
          const body = '// generated by tools/build_crossref_chunks.js — ' + M.global + ' for ' + slug + '\n'
            + '(function(){ var W = window;\n'
            + '  Object.assign(W.' + M.global + ' = W.' + M.global + ' || {}, '
            + JSON.stringify(perBook[slug]) + ');\n'
            + '  if (typeof W.__bomCrossrefsArrived === \'function\') W.__bomCrossrefsArrived();\n'
            + '})();\n';
          fs.writeFileSync(path.join(outDir, slug + '.js'), body);
          bytes += Buffer.byteLength(body);
          largest = Math.max(largest, Buffer.byteLength(body));
        }
        const whole = fs.statSync(path.join(ROOT, M.file)).size;
        console.log(`  bom ${M.global}: ${Object.keys(data).length} keys → ${slugs.length} chunks  `
          + `(was ${(whole / 1024).toFixed(0)} KB in one file; largest chunk ${(largest / 1024).toFixed(0)} KB)`);
      }
    }
  }
}

process.exit(failed ? 1 : 0);
