// Build imperatives.js — the pointed forms the Masoretic morphology parses as
// an IMPERATIVE, and nothing else.
//
//     node tools/build_imperatives.js
//
// WHY A SEPARATE FILE. attested_forms.js carries the full parse of all 54,896
// Masoretic forms and weighs 3.4 MB; it is precached but no page loads it, and
// pulling it in so the reader can lean on a command would be absurd. The
// imperatives are 889 forms — a few kilobytes — so they ship on their own.
//
// The parse is OpenScriptures + STEPBible TAHOT, not a guess from the letters:
// an imperative is HV<stem>v, e.g. HVqv2ms. Hebrew has no other reliable
// surface mark for one — לְכוּ "go" and לָקְחוּ "they took" differ by pointing
// alone — which is why this is the one place today a table beats the gloss.
const fs = require('fs'), path = require('path');
const ROOT = path.dirname(__dirname);
global.window = {};
require(path.join(ROOT, 'attested_forms.js'));
const A = global.window._attestedForms || {};

function pointedKey(s) {
  s = String(s || '').replace(/[֑-ֽֿ֯׀׃-׆]/g, '')
                     .replace(/\//g, '').replace(/ׇ/g, 'ָ');
  s = s.replace(/[^ְ-ּׁׂא-ת]/g, '');
  let out = '', i = 0;
  while (i < s.length) {
    const ch = s.charAt(i++), marks = [];
    while (i < s.length && s.charCodeAt(i) < 0x05D0) marks.push(s.charAt(i++));
    out += ch + marks.sort().join('');
  }
  return out;
}
/* FORMS THE MASORETIC TEXT NEVER INFLECTS, ADDED BY HAND.
   The table above is every imperative the MT happens to contain, and the MT is
   a ~300,000-word sample, not the boundary of Hebrew. An imperative carrying an
   OBJECT SUFFIX is the gap it leaves: הׇרְגֵהוּ "slay him" — the Spirit's command
   to Nephi in 1 Nephi 4:12 — parses to null, because the MT has הֲרֹג and never
   suffixes it.

   Recovering these by rule was tried and does not work. Stripping the suffix
   and matching consonants ignores the pointing, which is the only thing that
   distinguishes an imperative from a perfect here, and it returns "the day",
   "unto you", "Elijah" and "the vineyard" — 5,697 candidates, almost all
   wrong. So they are listed, one at a time, on the evidence of the gloss.
   ONE FORM AT A TIME, ON THE TRANSLATOR'S WORD. Four siblings were added
   here on the strength of their glosses — הׇרְגוֹ, הׇרְגֵנִי, הֲרֹגוּ, הִרְגוּ
   — and taken out again: the ruling was for this form, not for the pattern.
   This is the right place to add the next one when it is asked for. */
const EXTRA = [
  'הׇרְגֵהוּ'    // slay him — 1 Nephi 4:12, the Spirit to Nephi
];

const keys = {};
for (const form of Object.keys(A)) {
  if (/^HV.v/.test(A[form][1] || '')) keys[pointedKey(form)] = 1;
}
for (const form of EXTRA) keys[pointedKey(form)] = 1;

const out = path.join(ROOT, 'imperatives.js');
fs.writeFileSync(out,
  '// imperatives.js — auto-generated by tools/build_imperatives.js. DO NOT EDIT.\n' +
  '// The pointed forms the Masoretic morphology parses as an imperative\n' +
  '// (HV<stem>v), keyed by RootEngine.pointedKey. Sources: OpenScriptures\n' +
  '// Hebrew Bible and STEPBible TAHOT, both CC BY 4.0.\n' +
  'window.SW_IMPERATIVE = ' + JSON.stringify(keys) + ';\n');
console.log('imperative forms: %d (%d parsed + %d by hand)   %d KB',
            Object.keys(keys).length, Object.keys(keys).length - EXTRA.length,
            EXTRA.length, Math.round(fs.statSync(out).size / 1024));
