#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Extract the Hebrew verb-root inventory from Brauner's SHOROSHIM into
shoroshim_roots.js.  Usage: python3 tools/extract_shoroshim.py <shoroshim.pdf>
Requires pypdf.  The PDF is the translator's own copy and is not in this repo.

pypdf's layout mode emits the Hebrew in VISUAL (reversed) order on every page,
with the combining marks still trailing their base glyph — so each Hebrew run
is reversed unit-wise (base + marks travel together). The shin/sin dots and
dagesh are KEPT: Brauner's shin section splits between שׁ and שׂ (guideline 13)
and the dots are the only thing separating them. Finals are normalized to the
non-final letter, matching how the resolver keys families."""
import sys, re, os
sys.path.insert(0, os.path.expanduser('~/Library/Python/3.9/lib/python/site-packages'))
import pypdf

src = sys.argv[1] if len(sys.argv) > 1 else '~/Desktop/IIBS/shoroshim.pdf'
r = pypdf.PdfReader(os.path.expanduser(src))

MARKS = '\u05B0\u05B1\u05B2\u05B3\u05B4\u05B5\u05B6\u05B7\u05B8\u05B9\u05BA\u05BB\u05BC\u05BD\u05BF\u05C1\u05C2\u05C7'
LET = 'א-ת'
RUN = re.compile('[' + LET + '][' + LET + MARKS + ']*')
FIN = {'ך': 'כ', 'ם': 'מ', 'ן': 'נ', 'ף': 'פ', 'ץ': 'צ'}

def units(s):
    out = []
    for ch in s:
        if ch in MARKS and out: out[-1] += ch
        else: out.append(ch)
    return out

def unreverse(run):
    """visual -> logical: reverse the letter units, marks staying attached."""
    u = units(run)
    u.reverse()
    s = ''.join(u)
    return ''.join(FIN.get(c, c) for c in s)

def letters(s):
    return re.sub('[' + MARKS + ']', '', s)

roots, seealso = set(), set()
for i, page in enumerate(r.pages):
    if i < 9:                                   # front matter + guidelines
        continue
    text = page.extract_text(extraction_mode='layout') or ''
    for line in text.split('\n'):
        line = line.rstrip()
        if not line.strip() or 'SHOROSHIM' in line: continue
        runs = RUN.findall(line)
        if not runs: continue
        fixed = [unreverse(x) for x in runs]
        fixed = [x for x in fixed if 2 <= len(letters(x)) <= 5]
        if not fixed: continue
        is_see = 'See' in line
        # rightmost printed run = first logical run = the entry root of this line
        head = fixed[0]
        if is_see:
            # "See X" (and comma lists) — every run is a root name; the entry
            # this line belongs to was already captured from its heading line.
            seealso.update(fixed)
        else:
            roots.add(head)
            seealso.update(fixed[1:])           # comma-doubled headings: ככשׂ ,ככס

allroots = sorted(roots | seealso)
per = {}
for x in allroots: per[letters(x)[0]] = per.get(letters(x)[0], 0) + 1
expect = {'א':202,'ב':160,'ג':137,'ד':121,'ה':159,'ו':9,'ז':93,'ח':202,'ט':86,'י':123,
          'כ':132,'ל':101,'מ':171,'נ':203,'ס':168,'ע':182,'פ':196,'צ':119,'ק':163,
          'ר':164,'ש':294,'ת':121}
print('total: %d (Brauner: 3306)' % len(allroots))
for L in expect:
    print(' %s %3d / %3d' % (L, per.get(L, 0), expect[L]))

hdr = """// shoroshim_roots.js — Hebrew verb-root inventory.
// Extracted from SHOROSHIM: The Ultimate and Unique English Thesaurus of
// Hebrew Verb Roots, compiled by Reuven Brauner (c) 2014, Raanana, Israel.
// Used here as a VALIDATION set: a resolver result that is not a real root
// is a peel that has gone wrong. Brauner's own guideline 4 — "two or five
// letter roots are typically found under their basic three-letter root" —
// is why a two-letter residue is never itself an answer. Shin/sin dots and
// dagesh are preserved (guideline 13: an unpointed ש must check BOTH).
// Generated by tools/extract_shoroshim.py. DO NOT EDIT BY HAND.
"""
import json
out = hdr + 'window._shoroshimRoots = ' + json.dumps(allroots, ensure_ascii=False) + ';\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shoroshim_roots.js'), 'w', encoding='utf-8').write(out)
print('shoroshim_roots.js written: %d roots' % len(allroots))
