#!/usr/bin/env node
/* build_vocab_path.js — generates vocab_path.js, the graded vocabulary list.
 *
 * The reading order is not editorial: it is the corpus's own frequency order,
 * read straight out of root_concordance.js (which already counts every family
 * per volume). The one judgement here is what to SHOW for a family — its
 * dictionary lemma rather than its bare key, because a key like H5921 or a
 * bare triliteral is not what a learner writes on a card.
 *
 * Run after tools/build_root_concordance.js. Bump VP_V in vocabulary.html.
 */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
const win = {};
for (const f of ['root_concordance.js', 'bom/roots_glossary.js'])
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), { window: win }, { filename: f });
const C = win._rootConcordance, G = win._rootGlossaryData;

const TOP = 1000;                    // 1,000 roots is ~98% of the Book of Mormon
const NIQ = /[֑-ׇ]/;

/* The headword. A sense line opens "(לֶמָּה) …" — that pointed lemma is the
   dictionary form and the thing to memorise. Failing that, the commonest
   surface in the corpus, which is at least a real word. Failing that, the key. */
const HEB = /[\u05D0-\u05EA]/;
function lemmaOf(key, e) {
  const m = G[key] && /^\s*\(([^)]+)\)/.exec(G[key].meaning || '');
  /* Only if what stands in those parentheses is actually Hebrew. Some sense
     lines open with an English description instead — "direct object marker"
     for H0853 — and that is a gloss, not a headword. */
  if (m && HEB.test(m[1])) return m[1].replace(/\s+(I|II|III|IV)\s*$/, '').trim();
  const forms = Object.entries(e.f || {}).sort((a, b) => b[1] - a[1]).filter(f => HEB.test(f[0]));
  const pointed = forms.find(f => NIQ.test(f[0]));
  return (pointed || forms[0] || [key])[0];
}

/* The gloss. The sense line's first segment, minus its lemma — that is the
   sense the family is named for. Otherwise the commonest gloss in the corpus. */
function glossOf(key, e) {
  const mean = (G[key] && G[key].meaning) || '';
  if (mean) {
    const first = mean.split(/;\s*/)[0].trim();
    const head = /^\s*\(([^)]+)\)\s*/.exec(first);
    /* Strip the leading parenthetical only when it is the Hebrew lemma. When it
       is English it IS the definition — H0853 is "(direct object marker)" and
       nothing else, and its commonest corpus gloss ("them") describes whatever
       noun it happened to mark. */
    const body = (head && HEB.test(head[1])) ? first.slice(head[0].length).trim() : first.replace(/^\(|\)$/g, '').trim();
    if (body) return body.split(' — ')[0].trim();
  }
  const g = Object.entries(e.g || {}).sort((a, b) => b[1] - a[1])[0];
  return g ? g[0] : '';
}

/* Names are worth knowing but are not vocabulary: nobody memorises Zarahemla
   the way they memorise "to speak", so the page marks them. The test is the
   glossary's own category and NOTHING else — a capitalised gloss is not a
   name (מָשַׁח "to anoint" glosses "Messiah" and is a verb). */
function isName(key, e) {
  const cat = (G[key] || {}).category;
  return cat === 'Names' || cat === 'Name' || cat === 'Place';
}

const out = { v: 1, built: new Date().toISOString().slice(0, 10), vols: C.vols, volNames: C.volNames, totals: {}, lists: {} };
for (let vi = 0; vi < C.vols.length; vi++) {
  const vol = C.vols[vi];
  const rows = [];
  let total = 0;
  C.keys.forEach((k, i) => {
    const n = (C.roots[i].c || [])[vi] || 0;
    if (!n) return;
    total += n;
    rows.push({ k, i, n });
  });
  rows.sort((a, b) => b.n - a.n || a.k.localeCompare(b.k));
  out.totals[vol] = total;
  let run = 0;
  out.lists[vol] = rows.slice(0, TOP).map(r => {
    const e = C.roots[r.i];
    run += r.n;
    return [lemmaOf(r.k, e), glossOf(r.k, e), r.n, +(100 * run / total).toFixed(2), r.k, isName(r.k, e) ? 1 : 0];
  });
}
const body =
  '// vocab_path.js — auto-generated by tools/build_vocab_path.js. DO NOT EDIT.\n' +
  '// The ' + TOP + ' commonest root families of each volume, in the corpus’s own\n' +
  '// frequency order, with the share of the running text each one closes over.\n' +
  '// Row: [lemma, gloss, count, cumulative %, family key, isName]\n' +
  'window._vocabPath = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'vocab_path.js'), body);
const kb = (Buffer.byteLength(body) / 1024).toFixed(0);
console.log('[vocab] wrote vocab_path.js  ' + kb + ' KB');
for (const v of C.vols) {
  const L = out.lists[v];
  const at = n => (L[n - 1] ? L[n - 1][3].toFixed(1) + '%' : '—');
  console.log('  ' + v.padEnd(4) + String(out.totals[v]).padStart(8) + ' tokens   ' +
    '100:' + at(100).padStart(6) + '   300:' + at(300).padStart(6) +
    '   500:' + at(500).padStart(6) + '   1000:' + at(1000).padStart(6));
}
